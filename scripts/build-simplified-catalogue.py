def outputs(catalogue):
    """{path: text} for everything this script owns."""
    out = {
        CATALOGUE: json.dumps(catalogue, indent=2, ensure_ascii=False) + "\n",
        SIMPLIFIED / "index.html": render_landing(catalogue),
    }
    for module in catalogue["modules"]:
        target = SIMPLIFIED / "modules" / module["moduleSlug"] / "index.html"
        out[target] = render_module(catalogue, module)
    return out


def main():
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="verify the generated files are up to date, write nothing")
    ap.add_argument("--quiet", action="store_true", help="only report problems")
    args = ap.parse_args()

    activities = read_activities()
    try:
        validate(activities)
    except Invalid as error:
        print("Simplified Edition structure is invalid:\n%s" % error, file=sys.stderr)
        return 1

    catalogue = build_catalogue(activities)
    files = outputs(catalogue)

    if args.check:
        stale = []
        for path, text in sorted(files.items()):
            rel = path.relative_to(REPO)
            if not path.exists():
                stale.append("%s: missing" % rel)
            elif path.read_text(encoding="utf-8") != text:
                stale.append("%s: out of date" % rel)
            elif not args.quiet:
                print("ok: %s" % rel)
        if stale:
            print("\nStale generated files:", file=sys.stderr)
            for line in stale:
                print("  %s" % line, file=sys.stderr)
            print("\nRun: python3 scripts/build-simplified-catalogue.py",
                  file=sys.stderr)
            return 1
        print("\nAll %d generated files are up to date. %d activities across "
              "%d modules." % (len(files), catalogue["activityCount"],
                               len(catalogue["modules"])))
        return 0

    for path, text in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        if not args.quiet:
            print("wrote: %s" % path.relative_to(REPO))

    counts = ", ".join("%s %d" % (m["moduleSlug"], m["activityCount"])
                       for m in catalogue["modules"])
    print("\n%d activities: %s" % (catalogue["activityCount"], counts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
