    for entries in by_module.values():
        entries.sort(key=lambda a: a["toolSlug"])

    modules = []
    for spec in MODULES:
        slug = spec["moduleSlug"]
        entries = by_module[slug]
        modules.append({
            "id": slug,
            "moduleSlug": slug,
            "module": entries[0]["module"],
            "number": spec["number"],
            "path": "simplified/modules/%s/index.html" % slug,
            "activitiesDirectory": "simplified/modules/%s/tools/" % slug,
            "summary": spec["blurb"],
            "activityCount": len(entries),
            "activities": [catalogue_entry(a) for a in entries],
        })

