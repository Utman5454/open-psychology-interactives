# A chevron for the "open this" affordance on a card. Inline SVG rather than a
# character, because the arrow glyphs that render well are not all present in
# every system font stack, and a missing one leaves a tofu box in the corner of
# every card. aria-hidden throughout: the card's link already says where it
# goes, and "Open, arrow, Posner Spatial Cueing" is worse than "Posner Spatial
# Cueing" for anyone listening to it.
ARROW = ('<svg class="go-arrow" viewBox="0 0 16 16" width="13" height="13" '
         'aria-hidden="true" focusable="false"><path d="M6 3.5 10.5 8 6 12.5" '
         'fill="none" stroke="currentColor" stroke-width="2" '
         'stroke-linecap="round" stroke-linejoin="round"/></svg>')


def minutes_span(activities):
    """`5 to 7` for a module whose activities vary, `6` for one that does not."""
    low = min(a["estimatedMinutes"] for a in activities)
    high = max(a["estimatedMinutes"] for a in activities)
    return "%d" % low if low == high else "%d to %d" % (low, high)


def chip(text, figure=None):
    """A small count. The figure is a separate span so it can be sized up
    without the word beside it growing too."""
    if figure is None:
        return '<li class="chip">%s</li>' % esc(text)
    return ('<li class="chip"><span class="chip__figure">%s</span> %s</li>'
            % (esc(str(figure)), esc(text)))


def motif_figure(module_slug):
    """The module's own small figure, or nothing if it has none.

    Wrapped in a <figure> with a visible caption, so the point it makes is
    also made in words. The SVG is labelled rather than hidden: it is carrying
    an idea, not ornamenting one.
    """
    motif = MOTIFS.get(module_slug)
    if not motif:
        return ""
    ident = "motif-%s" % module_slug
    return """  <figure class="module-motif">
    <svg class="motif motif--{slug}" viewBox="0 0 240 140" role="img"
         aria-labelledby="{id}-title {id}-desc">
      <title id="{id}-title">{title}</title>
      <desc id="{id}-desc">{desc}</desc>{svg}    </svg>
    <figcaption class="module-motif__caption">{caption}</figcaption>
  </figure>
""".format(slug=esc(module_slug), id=ident, title=esc(motif["title"]),
           desc=esc(motif["desc"]), svg=motif["svg"],
           caption=esc(motif["caption"]))


