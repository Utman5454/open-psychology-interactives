def catalogue_entry(a):
    """One activity, carrying what a listing or a navigation link needs and
    nothing else. The full metadata stays in the activity's own file."""
    return {
        "id": a["id"],
        "title": a["title"],
        "module": a["module"],
        "moduleSlug": a["moduleSlug"],
        "toolSlug": a["toolSlug"],
        "path": "simplified/modules/%s/tools/%s/index.html"
                % (a["moduleSlug"], a["toolSlug"]),
        "summary": a["summary"],
        "teachingJob": a["readmeTopic"],
        "topics": a["topics"],
        "estimatedMinutes": a["estimatedMinutes"],
        "difficulty": a["difficulty"],
        "status": a["status"],
        "version": a["version"],
        "lastUpdated": a["lastUpdated"],
        "pairedWith": a["pairedWith"],
        "originalPath": a["originalPath"],
    }


# ------------------------------------------------------------------- pages

def esc(text):
    return html.escape(str(text), quote=True)


def opening_capital(text):
    """`readmeTopic` is written as a phrase that completes "this is about ...",
    so it starts lowercase. Standing on its own under a title it reads as an
    unfinished sentence, so the first letter is raised for display only. The
    catalogue keeps the metadata's own wording untouched.

    Checked against all 75: the only entry that does not begin with an
    ordinary word is "p-values as tail areas", and "P-values" is correct at
    the start of a sentence."""
    return text[:1].upper() + text[1:] if text else text


def number_of(tool_slug):
    """The leading number in a tool slug, for display. Every slug in both
    editions is `NN-name`; anything else is shown as it is."""
    head = tool_slug.split("-", 1)[0]
    return head if head.isdigit() else ""


