#!/usr/bin/env python3
"""Generate the Simplified Edition catalogue and its browsing pages.

    python3 scripts/build-simplified-catalogue.py
    python3 scripts/build-simplified-catalogue.py --check    # verify, do not write

The 75 `simplified/modules/*/tools/*/metadata.json` files are the source of
truth. This script reads them, validates the edition's structure, and writes:

    data/catalogue-simplified.json      the machine-readable index
    simplified/index.html               the edition landing page
    simplified/modules/<slug>/index.html  five module pages

Nothing here is hand-maintained. Editing a generated file directly is a
mistake the `--check` mode is there to catch: it regenerates everything in
memory and reports any file whose contents differ, so a stale page cannot be
committed unnoticed.

Why the module pages are generated rather than rendered in the browser
----------------------------------------------------------------------
The original edition's module pages fetch `data/catalogue.json` and fall back
to a static "in preparation" message. That is right for a collection which is
still filling up. This edition is complete, and its activities are built to
keep working from a downloaded folder with no server, so its module pages are
written out in full instead: they need no JavaScript, no fetch and no origin,
and they cannot disagree with the catalogue because both come from the same
run of this script.

The catalogue is still a real, loadable artefact. `simplified/assets/js/
edition-nav.js` reads it at runtime for the previous/next links inside an
activity, which is the one place a lookup genuinely needs to happen live.

Status
------
`assets/js/main.js` renders an original-edition tool only when its status is
exactly "published". This script applies the equivalent gate at generation
time: an activity whose status is "planned" or "in-progress" is a hard error
rather than a silent omission, because a Simplified Edition activity that
exists on disk but is missing from its module page is a worse failure than a
loud one. See the report in docs/simplified-edition-integration.md for the
recommendation on moving the edition off "draft" before deployment.
"""

