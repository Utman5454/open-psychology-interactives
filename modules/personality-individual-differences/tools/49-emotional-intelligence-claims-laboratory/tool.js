  /* =======================================================================
     The claims
     -------------------------------------------------------------------
     Each claim is judged against the matrix as currently set, not against a
     stored answer key, so a student who changes the settings changes what
     the evidence supports — which is the point.
     ===================================================================== */

  var CLAIMS = [
    {
      id: "distinct",
      judge: function (coef) {
        var overlap = r(coef, "sr", "pq");
        var gain = rSquared(coef, BASELINE.concat(["sr"]), "se") - rSquared(coef, BASELINE, "se");
        var verdict = overlap >= 0.45 && gain < 0.05 ? "no"
          : overlap < 0.30 && gain >= 0.05 ? "yes" : "partly";
        return {
          verdict: verdict,
          evidence:
            "The scale correlates " + fmt(overlap) + " with an ordinary " +
            "personality questionnaire, and adding it to a personality " +
            "questionnaire and a reasoning test changes the variance " +
            "accounted for in observed effectiveness by " +
            (gain >= 0 ? "+" : "") + pct(gain) + ".",
          teaching:
            "\"Measures something else\" is a claim about discriminant and " +
            "incremental validity, and both are testable. A questionnaire " +
            "that overlaps heavily with existing questionnaires and adds " +
            "little to prediction has not earned a new name, however good " +
            "the name is."
        };
      }
    },
    {
      id: "beatsiq",
      judge: function (coef) {
        var ei = r(coef, "sr", "se");
        var iq = r(coef, "rt", "se");
        var gain = rSquared(coef, BASELINE.concat(["sr"]), "se") - rSquared(coef, BASELINE, "se");
        var verdict = ei > iq + 0.10 && gain >= 0.05 ? "yes"
          : ei > iq + 0.05 ? "partly" : "no";
        return {
          verdict: verdict,
          evidence:
            "The self-report scale correlates " + fmt(ei) + " with observed " +
            "effectiveness and the reasoning test " + fmt(iq) + ". Once the " +
            "personality questionnaire is also in the model, the self-report " +
            "scale adds " + (gain >= 0 ? "+" : "") + pct(gain) + ".",
          teaching:
            "Two comparisons are being run together. A measure can have the " +
            "larger raw correlation and still add almost nothing, because " +
            "what it predicts was already predicted more cheaply. Beating " +
            "the reasoning test is not beating the questionnaire."
        };
      }
    },
    {
      id: "ability",
      /* The comparison has to be against a measure that is unambiguously
         about self-image, which is the personality questionnaire — not the
         self-report EI scale, whose own content the student can change. */
      judge: function (coef) {
        var withQuestionnaire = r(coef, "mp", "pq");
        var withReasoning = r(coef, "mp", "rt");
        var verdict = withQuestionnaire < 0.25 && withReasoning >= 0.25 ? "yes"
          : withQuestionnaire >= 0.45 ? "no" : "partly";
        return {
          verdict: verdict,
          evidence:
            "The emotion-management task correlates " + fmt(withQuestionnaire) +
            " with a self-description questionnaire and " + fmt(withReasoning) +
            " with a verbal reasoning test.",
          teaching:
            "A task sitting with the reasoning test rather than with the " +
            "questionnaire is behaving like a test. Two cautions either way: " +
            "it shares variance with ordinary reasoning, and a consensus key " +
            "defines the right answer by what most people say."
        };
      }
    },
    {
      id: "oneconstruct",
      judge: function (coef) {
        var pairs = [["sr", "mp"], ["sr", "er"], ["mp", "er"]];
        var lowest = pairs.reduce(function (low, pair) {
          return Math.min(low, r(coef, pair[0], pair[1]));
        }, 1);
        var verdict = lowest >= CONVERGENT ? "yes" : lowest >= 0.25 ? "partly" : "no";
        return {
          verdict: verdict,
          evidence:
            "The weakest correlation among the three measures carrying the " +
            "label is " + fmt(lowest) + " (" + band(lowest) + ").",
          teaching:
            "Convergence is decided by the weakest link, which is why the " +
            "number above is the minimum of the three. A small minimum means " +
            "a family of loosely related things sharing a name."
        };
      }
    },
    {
      id: "predicts",
      judge: function (coef) {
        var value = r(coef, "er", "se");
        var verdict = value >= 0.50 ? "yes" : value >= 0.35 ? "partly" : "no";
        return {
          verdict: verdict,
          evidence:
            "Emotion-recognition accuracy correlates " + fmt(value) +
            " with observed effectiveness, which is " + pct(value * value) +
            " of the variance in it.",
          teaching:
            "Two problems, and the second is the serious one. The " +
            "association leaves most differences between people unexplained " +
            "— and \"shows you will be\" turns an average across a sample " +
            "into a claim about one person, which no correlation licenses at " +
            "any size."
        };
      }
    }
  ];

  var VERDICT_WORDS = {
    yes: "Supported by this evidence",
    partly: "Partly supported",
    no: "Not supported by this evidence"
  };

  claimsForm.addEventListener("submit", function (event) {
    event.preventDefault();

    if (state.stage === "predict") {
      showFeedback(claimsFeedback, "caution", "Open the laboratory first.",
        "These claims are judged against the evidence in the matrix above, " +
        "so the laboratory needs to be open before the answers mean anything.");
      return;
    }

    var answers = CLAIMS.map(function (claim) {
      var picked = $('input[name="claim-' + claim.id + '"]:checked', claimsForm);
      return picked ? picked.value : null;
    });

    if (answers.indexOf(null) !== -1) {
      showFeedback(claimsFeedback, "caution", "One judgement per claim, please.",
        "Every claim needs an answer before the evidence is worth going " +
        "through — a blank is not a verdict.");
      return;
    }

    var coef = coefficients(state);
    var results = CLAIMS.map(function (claim, index) {
      var judged = claim.judge(coef);
      return { claim: claim, judged: judged, answer: answers[index] };
    });
    var agreed = results.filter(function (item) {
      return item.answer === item.judged.verdict;
    }).length;

    clear(claimsFeedback);
    claimsFeedback.setAttribute("data-tone", agreed >= 4 ? "good" : "caution");

    var lead = make("p");
    lead.appendChild(make("strong", "feedback__verdict",
      agreed + " of your 5 judgements match what the current evidence supports."));
    lead.appendChild(document.createTextNode(
      " The verdicts below are worked out from the matrix as you have it set, " +
      "not from a stored answer key. Change the settings and some of them change."));
    claimsFeedback.appendChild(lead);

    var list = make("ol", "claims__results");
    results.forEach(function (item, index) {
      var li = make("li");
      li.setAttribute("data-agreed", item.answer === item.judged.verdict ? "yes" : "no");

      var heading = make("p", "claims__result-head");
      heading.appendChild(make("strong", null,
        "Claim " + (index + 1) + ": " + VERDICT_WORDS[item.judged.verdict] + "."));
      heading.appendChild(document.createTextNode(
        item.answer === item.judged.verdict
          ? " That is what you said."
          : " You said: " + VERDICT_WORDS[item.answer].toLowerCase() + "."));
      li.appendChild(heading);

      li.appendChild(make("p", "claims__evidence", item.judged.evidence));
      li.appendChild(make("p", null, item.judged.teaching));
      list.appendChild(li);
    });
    claimsFeedback.appendChild(list);
    claimsFeedback.hidden = false;

    shell.announce("Five claims judged. " + agreed + " of your answers match the evidence.",
      { immediate: true });
  });

