/* =========================================================================
   Emotional-Intelligence Claims Laboratory
   -------------------------------------------------------------------------
   Six fictional measures, one correlation matrix, and a set of marketing
   claims that students judge against it. Four of the measures carry the
   emotional-intelligence label or are the outcome it is sold on; two are the
   ordinary comparison measures any claim of added value has to beat.

   THE EDUCATIONAL MODEL
   ---------------------
   Every measure is written as a weighted sum of independent standard normal
   sources, scaled so the measure itself has unit variance:

       z(measure) = P·dispositional + A·emotion ability + G·general cognitive
                    + Q·questionnaire method + T·testing method + unique

   Because the sources are independent, the model-implied correlation between
   two measures is just the sum of the products of their shared coefficients:

       r(x, y) = Px·Py + Ax·Ay + Gx·Gy + Qx·Qy + Tx·Ty

   The two method coefficients are the reason two questionnaires correlate a
   little beyond what they have in common in content, and the reason two
   timed tests do. They are sliders because "it is all method variance" is a
   claim students should be able to test rather than assert: turning the
   questionnaire method effect to zero still leaves the self-report scale
   correlating strongly with the personality questionnaire, because that
   overlap is dispositional content, not shared format.

   THE ORGANISING THREAD
   ---------------------
   Self-report EI overlaps a personality questionnaire. Ability EI overlaps a
   reasoning test. Therefore the question worth asking is whether either adds
   anything beyond those. The activity is that sentence, in two steps.

   Step 1 shows the two overlaps as two bars, with a third bar for how little
   the two EI measures agree with each other - the contrast that makes the
   question bite. One control: the mix slider, which asks what the evidence
   would look like if the self-report label were honest. The full 6x6 matrix is
   the evidence behind the bars and sits in a disclosure; the two method sliders
   and their presets sit in another.

   Step 2 asks the question the overlaps raise: does either EI measure predict
   observed effectiveness once a personality questionnaire and a reasoning test
   are already in the model? One radio, one table, one sentence.

   THE ONE SLIDER THAT MATTERS MOST
   --------------------------------
   The self-report scale's content is a fixed amount of common variance split
   between two sources by one angle:

       P = 0.72·cos(theta),  A = 0.72·sin(theta),  theta = mix · 90 degrees

   At mix = 0 the scale is a personality questionnaire with a different name.
   At mix = 1 it is a genuine indicator of emotion ability, and correlates
   with the performance tasks accordingly. The total amount of construct
   variance never changes, so students cannot make the scale better simply by
   sliding — only differently pointed. That is the whole argument of the tool
   in one control.

   INCREMENTAL VALIDITY
   --------------------
   Regression is run properly on the model-implied correlation matrix:
   standardised weights come from solving R·b = r by Gaussian elimination and
   R-squared is b·r. The baseline is deliberately the pair a sceptical
   reviewer would demand — a broad personality questionnaire and a reasoning
   test — because "correlates with the outcome" and "adds anything you did
   not already have" are different claims.

   WHAT THIS IS NOT
   ----------------
   No published emotional-intelligence measure is reproduced, quoted,
   paraphrased or scored. The six measures are fictional descriptions of
   method types, the correlations are generated by the model above, and no
   number here is an estimate of any real quantity. The tool takes no view on
   whether emotional intelligence exists; it is about what a correlation
   matrix can and cannot license someone to advertise.

   No data leave the browser. There is no storage and no network request.
   ========================================================================= */

