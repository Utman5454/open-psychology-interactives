  function fmt(v) {
    var s = (Math.abs(v) < 0.005 ? 0 : v).toFixed(2);
    return s.charAt(0) === "0" ? s.slice(1) : (s.slice(0, 2) === "-0" ? "-" + s.slice(2) : s);
  }

  function pct(v) { return Math.round(v * 100) + "%"; }

  function band(value) {
    var a = Math.abs(value);
    if (a < 0.10) { return "near zero"; }
    if (a < 0.30) { return "small"; }
    if (a < 0.50) { return "moderate"; }
    return "large";
  }

  function measureById(id) {
    for (var i = 0; i < MEASURES.length; i += 1) {
      if (MEASURES[i].id === id) { return MEASURES[i]; }
    }
    return null;
  }

  function nameOf(id) { return measureById(id).name; }
  function shortOf(id) { return measureById(id).short; }

  function listNames(ids) {
    var names = ids.map(nameOf).map(function (n) { return n.toLowerCase(); });
    if (names.length === 1) { return names[0]; }
    return names.slice(0, -1).join(", ") + " and " + names[names.length - 1];
  }

