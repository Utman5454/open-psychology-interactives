  /**
   * The deadline paraphrases not already in the student's Round 2 scale.
   * @returns {string[]}
   */
  function transferAdditions() {
    return ITEMS.filter(function (item) {
      return (
        item.family === "deadline" && state.roundTwo.ids.indexOf(item.id) === -1
      );
    })
      .slice(0, 4)
      .map(function (item) {
        return item.id;
      });
  }

  function applyTransfer(event) {
    event.preventDefault();

    var alphaGuess = transferForm.querySelector(
      'input[name="transfer-alpha"]:checked'
    );
    var outcomeGuess = transferForm.querySelector(
      'input[name="transfer-outcome"]:checked'
    );

    if (!alphaGuess || !outcomeGuess) {
      transferError.textContent =
        "Answer both parts before applying the change.";
      transferError.hidden = false;
      return;
    }
    transferError.hidden = true;

    var before = state.roundTwo;
    var after = computeMetrics(before.ids.concat(transferAdditions()));

    var alphaDirection = direction(before.alpha, after.alpha);
    var outcomeDirection = direction(before.outcome, after.outcome);

    // Show the enlarged scale in the builder so the change is visible, not
    // merely asserted. The Round 2 snapshot behind the comparison table is
    // left untouched.
    setSelection(after.ids);

    var gotAlpha = alphaGuess.value === alphaDirection;
    var gotOutcome = outcomeGuess.value === outcomeDirection;
    var tone = gotAlpha && gotOutcome ? "good" : "caution";
    var verdict =
      gotAlpha && gotOutcome
        ? "Both right."
        : gotAlpha || gotOutcome
        ? "Half right."
        : "Not what happened.";

    showFeedback(
      transferFeedback,
      tone,
      verdict,
      "Alpha went from " +
        formatStat(before.alpha, 3) +
        " to " +
        formatStat(after.alpha, 3) +
        " (" +
        alphaDirection +
        "), while the correlation with the outcome went from " +
        formatStat(before.outcome, 3) +
        " to " +
        formatStat(after.outcome, 3) +
        " (" +
        outcomeDirection +
        "). Four items were added and the scale got worse at the job it " +
        "exists to do, while every conventional reliability statistic " +
        "improved. A reviewer who asks only for a higher alpha is asking for " +
        "this. The builder above now shows the enlarged scale; the comparison " +
        "table still shows your Round 2 scale as you submitted it."
    );

    shell.announce(
      "Applied. Alpha " +
        alphaDirection +
        " to " +
        formatStat(after.alpha) +
        "; outcome correlation " +
        outcomeDirection +
        " to " +
        formatStat(after.outcome) +
        ".",
      { immediate: true }
    );
  }

  /** Direction of travel, with a dead band so trivial moves read as "same". */
  function direction(before, after) {
    var change = after - before;
    if (Math.abs(change) < 0.005) {
      return "same";
    }
    return change > 0 ? "up" : "down";
  }

