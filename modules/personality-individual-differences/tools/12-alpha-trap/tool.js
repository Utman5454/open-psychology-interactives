  /**
   * Model-implied correlation between two items.
   * @param {object} a
   * @param {object} b
   * @returns {number}
   */
  function itemCorrelation(a, b) {
    var r = a.loadings.general * b.loadings.general;
    if (a.facet === b.facet) {
      r += a.loadings.facet * b.loadings.facet;
    }
    if (a.family && a.family === b.family) {
      r += a.loadings.wording * b.loadings.wording;
    }
    return r;
  }

  /**
   * Model-implied covariance between one item and the simulated outcome.
   * Both are standardised, so this is also their correlation.
   * @param {object} item
   * @returns {number}
   */
  function itemOutcomeCovariance(item) {
    return (
      CRITERION.general * item.loadings.general +
      (CRITERION.facets * item.loadings.facet) / Math.sqrt(FACETS.length)
    );
  }

  /**
   * Everything the page reports about one selection of items.
   * @param {string[]} ids
   * @returns {object}
   */
  function computeMetrics(ids) {
    var items = ids.map(function (id) {
      return ITEM_BY_ID[id];
    });
    var k = items.length;

    // Sum of the off-diagonal correlations, counted once per unordered pair.
    var pairSum = 0;
    var pairCount = 0;
    var i;
    var j;
    for (i = 0; i < k; i += 1) {
      for (j = i + 1; j < k; j += 1) {
        pairSum += itemCorrelation(items[i], items[j]);
        pairCount += 1;
      }
    }

    // Var(T) = sum of the whole correlation matrix; the diagonal is k ones.
    var varTotal = k + 2 * pairSum;
    var meanCorrelation = pairCount > 0 ? pairSum / pairCount : null;
    var alpha =
      k > 1 ? (k / (k - 1)) * (1 - k / varTotal) : null;

    // How many selected items sit in each wording family, so that a family
    // with two or more members can be called out as redundancy.
    var familyCounts = {};
    items.forEach(function (item) {
      if (item.family) {
        familyCounts[item.family] = (familyCounts[item.family] || 0) + 1;
      }
    });

    var duplicatePairs = 0;
    var repeatedFamilies = [];
    Object.keys(familyCounts).forEach(function (family) {
      var n = familyCounts[family];
      if (n > 1) {
        duplicatePairs += (n * (n - 1)) / 2;
        repeatedFamilies.push({ id: family, name: FAMILIES[family], count: n });
      }
    });
    repeatedFamilies.sort(function (a, b) {
      return b.count - a.count;
    });

    // Per-area counts, and how many of those items repeat another's wording.
    var facetCounts = {};
    FACETS.forEach(function (facet) {
      facetCounts[facet.id] = { total: 0, repeated: 0 };
    });
    items.forEach(function (item) {
      var cell = facetCounts[item.facet];
      cell.total += 1;
      if (item.family && familyCounts[item.family] > 1) {
        cell.repeated += 1;
      }
    });

    var breadth = FACETS.filter(function (facet) {
      return facetCounts[facet.id].total > 0;
    }).length;

    // r(T, Y). Var(Y) = 1 because Y is standardised, so the denominator is
    // the standard deviation of the total score alone.
    var outcome = null;
    if (k > 0) {
      var covariance = items.reduce(function (sum, item) {
        return sum + itemOutcomeCovariance(item);
      }, 0);
      outcome = covariance / Math.sqrt(varTotal);
    }

    return {
      ids: ids.slice(),
      k: k,
      alpha: alpha,
      meanCorrelation: meanCorrelation,
      varTotal: varTotal,
      breadth: breadth,
      facetCounts: facetCounts,
      familyCounts: familyCounts,
      duplicatePairs: duplicatePairs,
      repeatedFamilies: repeatedFamilies,
      outcome: outcome
    };
  }

  /**
   * Does this selection satisfy the Round 2 brief?
   * @param {object} metrics
   * @returns {object} { met:boolean, checks:[{label, met}] }
   */
  function roundTwoChecks(metrics) {
    var checks = [
      {
        label: "covers all five content areas",
        detail: metrics.breadth + " of " + ROUND_TWO.requiredFacets,
        met: metrics.breadth === ROUND_TWO.requiredFacets
      },
      {
        label: "no wording used twice",
        detail:
          metrics.duplicatePairs === 0
            ? "none"
            : metrics.duplicatePairs + " near-duplicate pairs",
        met: metrics.duplicatePairs === 0
      },
      {
        label:
          "between " + ROUND_TWO.minItems + " and " + ROUND_TWO.maxItems + " items",
        detail: metrics.k + " selected",
        met: metrics.k >= ROUND_TWO.minItems && metrics.k <= ROUND_TWO.maxItems
      },
      {
        label: "alpha at least " + formatStat(ROUND_TWO.minAlpha),
        detail: metrics.alpha === null ? "not yet" : formatStat(metrics.alpha),
        met: metrics.alpha !== null && metrics.alpha >= ROUND_TWO.minAlpha
      }
    ];

    return {
      met: checks.every(function (check) {
        return check.met;
      }),
      checks: checks
    };
  }

