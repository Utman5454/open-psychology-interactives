  /* --- The reveal -------------------------------------------------------
     Feedback is written from what the student actually built, so a student
     who resisted the trap is not told they fell into it. */

  function buildReveal(metrics) {
    while (revealBody.firstChild) {
      revealBody.removeChild(revealBody.firstChild);
    }

    var narrow = metrics.breadth <= 2;
    var clean = metrics.duplicatePairs === 0;
    var lead;

    if (narrow && !clean) {
      lead =
        "You reached alpha " +
        formatStat(metrics.alpha) +
        " — and built a scale that measures " +
        (metrics.breadth === 1 ? "one" : "two") +
        " of the five content areas.";
    } else if (clean && metrics.breadth >= 4) {
      lead =
        "You resisted the shortcut: alpha " +
        formatStat(metrics.alpha) +
        " with no repeated wording and " +
        metrics.breadth +
        " of the five areas covered.";
    } else {
      lead =
        "You reached alpha " +
        formatStat(metrics.alpha) +
        ", with " +
        metrics.duplicatePairs +
        " near-duplicate " +
        plural(metrics.duplicatePairs, "pair") +
        " and " +
        metrics.breadth +
        " of the five content areas covered.";
    }
    revealBody.appendChild(make("p", "reveal__lead", lead));

    var figures = make("ul", "reveal__figures");
    [
      ["Alpha", formatStat(metrics.alpha)],
      ["Items", String(metrics.k)],
      ["Content areas", metrics.breadth + " of " + FACETS.length],
      ["Near-duplicate pairs", String(metrics.duplicatePairs)],
      ["Correlation with outcome", formatStat(metrics.outcome)]
    ].forEach(function (pair) {
      var entry = make("li");
      entry.appendChild(make("span", "reveal__figure-label", pair[0]));
      entry.appendChild(make("span", "reveal__figure-value", pair[1]));
      figures.appendChild(entry);
    });
    revealBody.appendChild(figures);

    // The paraphrases doing the work, quoted back.
    if (metrics.repeatedFamilies.length > 0) {
      var worst = metrics.repeatedFamilies[0];
      revealBody.appendChild(
        make(
          "p",
          null,
          "The " +
            worst.count +
            " items below are all in your scale. They are the same question " +
            "about " +
            worst.name +
            ", asked " +
            worst.count +
            " times. Between them they contribute " +
            (worst.count * (worst.count - 1)) / 2 +
            " of the " +
            String((metrics.k * (metrics.k - 1)) / 2) +
            " correlations that alpha is averaging."
        )
      );
      var quoted = make("ul", "reveal__items");
      metrics.ids
        .filter(function (id) {
          return ITEM_BY_ID[id].family === worst.id;
        })
        .forEach(function (id) {
          quoted.appendChild(make("li", null, "“" + ITEM_BY_ID[id].text + "”"));
        });
      revealBody.appendChild(quoted);
    }

    // What the outcome correlation means, with an explicit counterfactual.
    var balanced = computeMetrics(EXAMPLES.round2);
    revealBody.appendChild(
      make(
        "p",
        null,
        "Your scale correlates " +
          formatStat(metrics.outcome) +
          " with a simulated outcome that depends on the whole construct. " +
          "For comparison, a ten-item scale covering all five areas with no " +
          "repeated wording reaches alpha " +
          formatStat(balanced.alpha) +
          " — lower than " +
          (metrics.alpha >= balanced.alpha ? "yours" : "many published scales") +
          " — but correlates " +
          formatStat(balanced.outcome) +
          " with the same outcome. The lower-alpha scale is the better measure."
      )
    );

    revealBody.appendChild(
      make(
        "p",
        null,
        "Alpha rises with the number of items and with their average " +
          "correlation. Paraphrasing an item raises both at once, so it is " +
          "the cheapest possible way to buy a high alpha — and it buys " +
          "nothing else. The extra shared variance is specific to the " +
          "wording, and the outcome does not care about wording."
      )
    );

    if (state.prediction) {
      revealBody.appendChild(buildPredictionComparison(metrics));
    }
  }

  function buildPredictionComparison(metrics) {
    var predictedBreadth = state.prediction.breadth;
    var actualBand =
      metrics.breadth <= 2 ? "one-or-two" : metrics.breadth === 3 ? "three" : "four-or-five";
    var breadthRight = predictedBreadth === actualBand;

    var predictedOutcome = state.prediction.outcome;
    var actualOutcomeBand =
      metrics.outcome < 0.45 ? "weak" : metrics.outcome < 0.55 ? "moderate" : "strong";
    var outcomeRight =
      predictedOutcome === actualOutcomeBand || predictedOutcome === "unknown";

    var text;
    if (predictedOutcome === "unknown") {
      text =
        "You predicted that alpha on its own would not tell you what " +
          "the scale correlates with. The observed correlation was " +
        formatStat(metrics.outcome) +
        ", and nothing about alpha would have let you anticipate it.";
    } else if (breadthRight && outcomeRight) {
      text =
        "Both of your predictions were borne out: " +
        metrics.breadth +
        " of five areas covered, and a correlation of " +
        formatStat(metrics.outcome) +
        " with the outcome.";
    } else {
      text =
        "Compare that with your prediction. You expected the scale to cover " +
        describeBreadthPrediction(predictedBreadth) +
        " and to correlate " +
        describeOutcomePrediction(predictedOutcome) +
        " with the outcome. It covered " +
        metrics.breadth +
        " of five, and correlated " +
        formatStat(metrics.outcome) +
        ".";
    }

    var node = make("p", "prediction__readback", text);
    return node;
  }

  function describeBreadthPrediction(value) {
    return value === "one-or-two"
      ? "one or two areas"
      : value === "three"
      ? "about three areas"
      : "four or five areas";
  }

  function describeOutcomePrediction(value) {
    return value === "weak"
      ? "weakly, around 0.2,"
      : value === "moderate"
      ? "moderately, around 0.4,"
      : "strongly, around 0.6,";
  }

  /* --- The comparison table --------------------------------------------- */

  function buildComparison(one, two) {
    while (comparisonBody.firstChild) {
      comparisonBody.removeChild(comparisonBody.firstChild);
    }

    [
      ["Items", String(one.k), String(two.k)],
      ["Cronbach's alpha", formatStat(one.alpha), formatStat(two.alpha)],
      [
        "Mean inter-item correlation",
        formatStat(one.meanCorrelation),
        formatStat(two.meanCorrelation)
      ],
      [
        "Content areas covered",
        one.breadth + " of " + FACETS.length,
        two.breadth + " of " + FACETS.length
      ],
      [
        "Near-duplicate pairs",
        String(one.duplicatePairs),
        String(two.duplicatePairs)
      ],
      [
        "Correlation with the simulated outcome",
        formatStat(one.outcome),
        formatStat(two.outcome)
      ]
    ].forEach(function (row) {
      var tr = make("tr");
      var th = make("th", null, row[0]);
      th.setAttribute("scope", "row");
      tr.appendChild(th);
      tr.appendChild(make("td", null, row[1]));
      tr.appendChild(make("td", null, row[2]));
      comparisonBody.appendChild(tr);
    });

    var alphaFell = two.alpha < one.alpha;
    var outcomeRose = two.outcome > one.outcome;

    comparisonVerdict.textContent = alphaFell && outcomeRose
      ? "Your Round 2 scale has the lower alpha and the higher correlation " +
        "with the outcome. If alpha were a measure of quality, that " +
        "combination could not happen."
      : outcomeRose
      ? "Your Round 2 scale correlates more strongly with the outcome. Alpha " +
        "did not have to fall for that to be true — the point is that the two " +
        "move independently."
      : "Compare the two columns row by row, and note which differences alpha " +
        "was sensitive to and which it was blind to.";
  }

