/* =========================================================================
   The Alpha Trap
   -------------------------------------------------------------------------
   Students build a scale from a fictional item bank and watch Cronbach's
   alpha respond. Because several items are deliberate paraphrases of one
   another, alpha can be pushed high by repetition alone — at which point the
   scale is revealed to correlate poorly with a simulated outcome.

   THE EDUCATIONAL MODEL
   ---------------------
   Every item is standardised (mean 0, variance 1) and generated by four
   independent standard-normal sources:

       X_i = g_i * G  +  f_i * F(facet)  +  w_i * W(wording family)  +  e_i

     G  a general "academic conscientiousness" factor shared by all items;
     F  a factor specific to one of the five content areas;
     W  a factor shared only by items that paraphrase each other — the
        wording-specific variance that produces a bloated specific factor;
     e  item-specific error, sized so the four coefficients give unit
        variance.

   Because the items are standardised, the correlation between two of them is

       r_ij = g_i g_j  +  f_i f_j [same area]  +  w_i w_j [same wording family]

   and Cronbach's alpha follows from the correlation matrix in the usual way.
   For standardised items the raw and standardised forms of alpha coincide;
   this file computes it from the total-score variance, which is the more
   familiar expression:

       alpha = (k / (k - 1)) * (1 - k / Var(T))

   The simulated outcome — fictional tutor-rated dependability — is

       Y = a * G  +  b * (F1 + F2 + F3 + F4 + F5) / sqrt(5)  +  noise

   so it responds to the general factor AND to breadth of content coverage,
   but is completely indifferent to wording-specific variance. Adding
   paraphrases therefore inflates Var(T) — the denominator of the validity
   coefficient — while contributing nothing to its numerator. That single
   asymmetry is the whole demonstration.

   DELIBERATE SIMPLIFICATIONS
   --------------------------
   * No sampling error. Every figure is the value the model implies for a
     population, not an estimate from a sample. A real alpha carries a
     confidence interval; the page says so, and the teaching notes say so.
   * Items are treated as continuous and standardised, so no distinction is
     drawn between alpha, standardised alpha and ordinal alpha.
   * A single wording family per content area, which makes the structure
     legible to a student in a seminar. Real item pools are messier.
   * Loadings are chosen so that the target of Round 1 is unreachable without
     repetition (the widest scale with no repeated wording reaches 0.844).
     That is a property of these numbers, not of alpha in general, and it is
     there to make the trap reliable in a classroom.

   No data leave the browser. There is no storage and no network request.
   ========================================================================= */

