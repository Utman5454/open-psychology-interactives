  function recordPrediction(event) {
    event.preventDefault();

    var breadth = predictionForm.querySelector(
      'input[name="predict-breadth"]:checked'
    );
    var outcome = predictionForm.querySelector(
      'input[name="predict-outcome"]:checked'
    );

    if (!breadth || !outcome) {
      predictionError.textContent =
        "Answer both questions before you begin. Committing to an answer " +
        "first is what makes the result worth seeing.";
      predictionError.hidden = false;
      return;
    }

    predictionError.hidden = true;
    state.prediction = { breadth: breadth.value, outcome: outcome.value };

    predictionReadback.textContent =
      "Recorded: you expect the scale to cover " +
      describeBreadthPrediction(breadth.value) +
      ", and " +
      (outcome.value === "unknown"
        ? "you do not expect alpha to tell you what it correlates with."
        : "to correlate " +
          describeOutcomePrediction(outcome.value).replace(/,$/, "") +
          " with the outcome.") +
      " You will be reminded of this after Round 1.";
    predictionReadback.hidden = false;

    lockPredictionForm();
    startRoundOne();
    root.scrollIntoView({ block: "start" });
    root.querySelector("input[type=checkbox]").focus();
  }

