  /* The chart repeats the table beneath it and is hidden from assistive
     technology, so it may use colour freely — but each bar still carries its
     own number as text, which is what makes it readable in greyscale. */
  function renderChart(metrics) {
    var NS = "http://www.w3.org/2000/svg";
    var ROW_HEIGHT = 34;
    var BAR_HEIGHT = 18;
    var UNIT = 34; // pixels per item; six items is the widest any area gets
    var BAR_X = 128;

    while (chart.firstChild) {
      chart.removeChild(chart.firstChild);
    }

    var defs = document.createElementNS(NS, "defs");
    var pattern = document.createElementNS(NS, "pattern");
    pattern.setAttribute("id", "alpha-trap-hatch");
    pattern.setAttribute("width", "6");
    pattern.setAttribute("height", "6");
    pattern.setAttribute("patternUnits", "userSpaceOnUse");
    pattern.setAttribute("patternTransform", "rotate(45)");
    var stripe = document.createElementNS(NS, "line");
    stripe.setAttribute("x1", "0");
    stripe.setAttribute("y1", "0");
    stripe.setAttribute("x2", "0");
    stripe.setAttribute("y2", "6");
    stripe.setAttribute("class", "chart__hatch");
    pattern.appendChild(stripe);
    defs.appendChild(pattern);
    chart.appendChild(defs);

    FACETS.forEach(function (facet, index) {
      var counts = metrics.facetCounts[facet.id];
      var y = 12 + index * ROW_HEIGHT;

      var label = document.createElementNS(NS, "text");
      label.setAttribute("x", String(BAR_X - 8));
      label.setAttribute("y", String(y + BAR_HEIGHT - 4));
      label.setAttribute("text-anchor", "end");
      label.setAttribute("class", "chart__label");
      label.textContent = facet.short;
      chart.appendChild(label);

      // A hairline baseline so an empty area still reads as an empty bar
      // rather than as a missing row.
      var baseline = document.createElementNS(NS, "line");
      baseline.setAttribute("x1", String(BAR_X));
      baseline.setAttribute("y1", String(y + BAR_HEIGHT));
      baseline.setAttribute("x2", String(BAR_X + 6 * UNIT));
      baseline.setAttribute("y2", String(y + BAR_HEIGHT));
      baseline.setAttribute("class", "chart__baseline");
      chart.appendChild(baseline);

      if (counts.total > 0) {
        var bar = document.createElementNS(NS, "rect");
        bar.setAttribute("x", String(BAR_X));
        bar.setAttribute("y", String(y));
        bar.setAttribute("width", String(counts.total * UNIT));
        bar.setAttribute("height", String(BAR_HEIGHT));
        bar.setAttribute("class", "chart__bar");
        chart.appendChild(bar);

        if (counts.repeated > 0) {
          var repeated = document.createElementNS(NS, "rect");
          repeated.setAttribute("x", String(BAR_X));
          repeated.setAttribute("y", String(y));
          repeated.setAttribute("width", String(counts.repeated * UNIT));
          repeated.setAttribute("height", String(BAR_HEIGHT));
          repeated.setAttribute("class", "chart__bar-repeat");
          chart.appendChild(repeated);
        }
      }

      var count = document.createElementNS(NS, "text");
      count.setAttribute("x", String(BAR_X + counts.total * UNIT + 8));
      count.setAttribute("y", String(y + BAR_HEIGHT - 4));
      count.setAttribute("class", "chart__count");
      count.textContent =
        counts.repeated > 0
          ? counts.total + " (" + counts.repeated + " repeated)"
          : String(counts.total);
      chart.appendChild(count);
    });

    renderChartTable(metrics);
  }

