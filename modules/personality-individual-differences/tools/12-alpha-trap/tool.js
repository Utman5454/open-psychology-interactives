  /* Loadings for the two kinds of item. Squares must not exceed 1; the
     remainder is item-specific error.
       distinct:   0.55^2 + 0.32^2          = 0.405, error 0.595
       paraphrase: 0.45^2 + 0.30^2 + 0.62^2 = 0.677, error 0.323
     The implied correlations are:
       two paraphrases of each other          0.677
       same area, differently worded          0.344
       same area, both distinct               0.405
       different areas                        0.203 to 0.303          */
